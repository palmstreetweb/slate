/**
 * Rasterize the Slate lockup SVG (same paths as SlateLogo.tsx) for auth emails.
 * Usage: node scripts/render-slate-lockup.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const logoSrc = readFileSync(resolve(root, 'examples/_admin/components/SlateLogo.tsx'), 'utf8');
const match = logoSrc.match(/const WORDMARK = "([^"]+)"/);
if (!match?.[1]) {
  throw new Error('Could not read WORDMARK from SlateLogo.tsx');
}

const svg = `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 388 120" width="1164" height="360">
  <defs>
    <linearGradient id="g" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#2C323D"/>
      <stop offset="1" stop-color="#1B1F26"/>
    </linearGradient>
  </defs>
  <rect x="3" y="3" width="114" height="114" rx="27" fill="url(#g)" stroke="#3A414F" stroke-width="1.2"/>
  <rect x="33" y="34" width="30" height="11" rx="5.5" fill="#E23B2D"/>
  <rect x="33" y="56" width="56" height="11" rx="5.5" fill="#F2EFE8"/>
  <rect x="33" y="78" width="40" height="11" rx="5.5" fill="#F2EFE8" opacity="0.78"/>
  <g transform="translate(146,97) scale(0.04901,-0.04901)">
    <path d="${match[1]}" fill="#F2EFE8"/>
  </g>
</svg>
`;

const svgPath = resolve(root, 'brand/slate-lockup.svg');
const pngPath = resolve(root, 'brand/slate-lockup.png');
const tsPath = resolve(root, 'neon/functions/auth-email/logoPng.ts');
writeFileSync(svgPath, svg);

const require = createRequire(import.meta.url);
const { Resvg } = require('@resvg/resvg-js');
const png = new Resvg(svg, {
  fitTo: { mode: 'width', value: 1164 },
  background: 'rgba(0,0,0,0)',
}).render().asPng();
writeFileSync(pngPath, png);
writeFileSync(
  tsPath,
  `/** Auto-generated by scripts/render-slate-lockup.mjs — do not edit. */\nexport const SLATE_LOCKUP_PNG_BASE64 = '${Buffer.from(png).toString('base64')}';\n`,
);
console.log(`Wrote ${pngPath} (${png.length} bytes) and ${tsPath}`);
